    UNION ALL SELECT 'x-customer:create', 'Customer create', 'CUSTOMER', 'Seeded RBAC: x-customer:create'
    UNION ALL SELECT 'x-customer:update', 'Customer update', 'CUSTOMER', 'Seeded RBAC: x-customer:update'
    UNION ALL SELECT 'x-customer:delete', 'Customer delete', 'CUSTOMER', 'Seeded RBAC: x-customer:delete'
    UNION ALL SELECT 'x-product:read', 'Product read', 'PRODUCT', 'Seeded RBAC: x-product:read'
    UNION ALL SELECT 'x-product:create', 'Product create', 'PRODUCT', 'Seeded RBAC: x-product:create'
    UNION ALL SELECT 'x-product:update', 'Product update', 'PRODUCT', 'Seeded RBAC: x-product:update'
    UNION ALL SELECT 'x-product:delete', 'Product delete', 'PRODUCT', 'Seeded RBAC: x-product:delete'
    UNION ALL SELECT 'x-product:unit', 'Product unit', 'PRODUCT', 'Seeded RBAC: x-product:unit'
    UNION ALL SELECT 'x-product:category', 'Product category', 'PRODUCT', 'Seeded RBAC: x-product:category'
    UNION ALL SELECT 'x-inventory:read', 'Inventory read', 'INVENTORY', 'Seeded RBAC: x-inventory:read'
    UNION ALL SELECT 'x-inventory:create', 'Inventory create', 'INVENTORY', 'Seeded RBAC: x-inventory:create'
    UNION ALL SELECT 'x-inventory:update', 'Inventory update', 'INVENTORY', 'Seeded RBAC: x-inventory:update'
    UNION ALL SELECT 'x-inventory:delete', 'Inventory delete', 'INVENTORY', 'Seeded RBAC: x-inventory:delete'
    UNION ALL SELECT 'x-inventory:stock-in', 'Inventory stock-in', 'INVENTORY', 'Seeded RBAC: x-inventory:stock-in'
    UNION ALL SELECT 'x-inventory:stock-out', 'Inventory stock-out', 'INVENTORY', 'Seeded RBAC: x-inventory:stock-out'
    UNION ALL SELECT 'x-inventory:reserve', 'Inventory reserve', 'INVENTORY', 'Seeded RBAC: x-inventory:reserve'
    UNION ALL SELECT 'x-order:read', 'Order read', 'ORDER', 'Seeded RBAC: x-order:read'
    UNION ALL SELECT 'x-order:create', 'Order create', 'ORDER', 'Seeded RBAC: x-order:create'
    UNION ALL SELECT 'x-order:update', 'Order update', 'ORDER', 'Seeded RBAC: x-order:update'
