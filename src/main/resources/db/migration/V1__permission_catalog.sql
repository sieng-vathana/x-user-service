    UNION ALL SELECT 'x-business:update', 'Business update', 'BUSINESS', 'Seeded RBAC: x-business:update'
    UNION ALL SELECT 'x-business:delete', 'Business delete', 'BUSINESS', 'Seeded RBAC: x-business:delete'
    UNION ALL SELECT 'x-store:read', 'Store read', 'STORE', 'Seeded RBAC: x-store:read'
    UNION ALL SELECT 'x-store:create', 'Store create', 'STORE', 'Seeded RBAC: x-store:create'
    UNION ALL SELECT 'x-store:update', 'Store update', 'STORE', 'Seeded RBAC: x-store:update'
    UNION ALL SELECT 'x-store:delete', 'Store delete', 'STORE', 'Seeded RBAC: x-store:delete'
