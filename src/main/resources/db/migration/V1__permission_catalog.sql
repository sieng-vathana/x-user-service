    UNION ALL SELECT 'x-delivery:read', 'Delivery read', 'DELIVERY', 'Seeded RBAC: x-delivery:read'
    UNION ALL SELECT 'x-delivery:create', 'Delivery create', 'DELIVERY', 'Seeded RBAC: x-delivery:create'
    UNION ALL SELECT 'x-delivery:update', 'Delivery update', 'DELIVERY', 'Seeded RBAC: x-delivery:update'
    UNION ALL SELECT 'x-delivery:delete', 'Delivery delete', 'DELIVERY', 'Seeded RBAC: x-delivery:delete'
    UNION ALL SELECT 'x-delivery:quote', 'Delivery quote', 'DELIVERY', 'Seeded RBAC: x-delivery:quote'
