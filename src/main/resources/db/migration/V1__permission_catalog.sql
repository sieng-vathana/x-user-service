    UNION ALL SELECT 'x-product:tax', 'Product tax', 'PRODUCT', 'Product Tax menu access'
) AS catalog
WHERE NOT EXISTS (
    SELECT 1 FROM permissions existing WHERE existing.permission_code = catalog.permission_code
);
