-- Every permission code the Merchant Portal checks.
-- Rows that already exist are left as they are, so this is safe on databases seeded by hand.

INSERT INTO permissions (permission_code, permission_name, module_name, description)
SELECT catalog.permission_code, catalog.permission_name, catalog.module_name, catalog.description
FROM (
    SELECT 'x-user:read' AS permission_code, 'User read' AS permission_name, 'USER' AS module_name, 'Seeded RBAC: x-user:read' AS description
    UNION ALL SELECT 'x-user:create', 'User create', 'USER', 'Seeded RBAC: x-user:create'
    UNION ALL SELECT 'x-user:update', 'User update', 'USER', 'Seeded RBAC: x-user:update'
    UNION ALL SELECT 'x-user:delete', 'User delete', 'USER', 'Seeded RBAC: x-user:delete'
    UNION ALL SELECT 'x-business:read', 'Business read', 'BUSINESS', 'Seeded RBAC: x-business:read'
